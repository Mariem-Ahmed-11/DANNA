function translateTemplate(value, map) {
  for (const [source, translated] of Object.entries(map)) {
    if (!source.includes('{')) continue
    const patternSource = source
      .split(/(\{\w+\})/)
      .map((part) => /^\{\w+\}$/.test(part)
        ? '(.+?)'
        : part.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'))
      .join('')
    const pattern = new RegExp(`^${patternSource}$`)
    const match = value.match(pattern)
    if (!match) continue
    let index = 1
    return translated.replace(/\{\w+\}/g, () => match[index++])
  }
  return value
}

