function translateValidationMessage(value, language) {
  const fieldLabel = (field) => (
    language === 'ar'
      ? validationFieldLabels[field] || 'البيانات'
      : englishValidationFieldLabels[field] || field.replaceAll('_', ' ')
  )

  if (language === 'ar') {
    let match = value.match(/^The ([\w.]+) field is required\.$/)
    if (match) return `حقل ${fieldLabel(match[1].split('.').pop())} مطلوب.`
    match = value.match(/^The ([\w.]+) field must be at least (\d+) characters?\.$/)
    if (match) return `يجب ألا يقل حقل ${fieldLabel(match[1].split('.').pop())} عن ${match[2]} حرفًا.`
    match = value.match(/^The ([\w.]+) field must not be greater than (\d+) characters?\.$/)
    if (match) return `يجب ألا يزيد حقل ${fieldLabel(match[1].split('.').pop())} على ${match[2]} حرفًا.`
    match = value.match(/^The ([\w.]+) field must be a valid email address\.$/)
    if (match) return `يجب إدخال بريد إلكتروني صالح في حقل ${fieldLabel(match[1].split('.').pop())}.`
    match = value.match(/^The ([\w.]+) field must be a valid URL\.$/)
    if (match) return `يجب إدخال رابط صالح في حقل ${fieldLabel(match[1].split('.').pop())}.`
    match = value.match(/^The ([\w.]+) field must be an integer\.$/)
    if (match) return `يجب إدخال عدد صحيح في حقل ${fieldLabel(match[1].split('.').pop())}.`
    match = value.match(/^The ([\w.]+) field must be numeric\.$/)
    if (match) return `يجب إدخال قيمة رقمية في حقل ${fieldLabel(match[1].split('.').pop())}.`
    match = value.match(/^The selected ([\w.]+) is invalid\.$/)
    if (match) return `القيمة المحددة في حقل ${fieldLabel(match[1].split('.').pop())} غير صالحة.`
    match = value.match(/^The ([\w.]+) field confirmation does not match\.$/)
    if (match) return `تأكيد حقل ${fieldLabel(match[1].split('.').pop())} غير متطابق.`
  } else {
    let match = value.match(/^حقل (.+) مطلوب\.$/)
    if (match) return `The ${englishValidationFieldLabels[match[1]] || match[1]} field is required.`
    match = value.match(/^يجب ألا يقل حقل (.+) عن (\d+) حرفًا\.$/)
    if (match) return `The ${englishValidationFieldLabels[match[1]] || match[1]} field must be at least ${match[2]} characters.`
    match = value.match(/^يجب ألا يزيد حقل (.+) على (\d+) حرفًا\.$/)
    if (match) return `The ${englishValidationFieldLabels[match[1]] || match[1]} field must not be greater than ${match[2]} characters.`
    match = value.match(/^يجب إدخال بريد إلكتروني صالح في حقل (.+)\.$/)
    if (match) return `The ${englishValidationFieldLabels[match[1]] || match[1]} field must be a valid email address.`
    match = value.match(/^يجب إدخال رابط صالح في حقل (.+)\.$/)
    if (match) return `The ${englishValidationFieldLabels[match[1]] || match[1]} field must be a valid URL.`
    match = value.match(/^يجب إدخال عدد صحيح في حقل (.+)\.$/)
    if (match) return `The ${englishValidationFieldLabels[match[1]] || match[1]} field must be an integer.`
    match = value.match(/^يجب إدخال قيمة رقمية في حقل (.+)\.$/)
    if (match) return `The ${englishValidationFieldLabels[match[1]] || match[1]} field must be numeric.`
    match = value.match(/^القيمة المحددة في حقل (.+) غير صالحة\.$/)
    if (match) return `The selected ${englishValidationFieldLabels[match[1]] || match[1]} is invalid.`
    match = value.match(/^تأكيد حقل (.+) غير متطابق\.$/)
    if (match) return `The ${englishValidationFieldLabels[match[1]] || match[1]} field confirmation does not match.`
  }

  return value
}

function localizeDocument(language) {
  const reverse = Object.fromEntries(Object.entries(translations).map(([english, translated]) => [translated, english]))
  const convert = (value) => {
    const dictionary = language === 'ar' ? translations : reverse
    const exact = dictionary[value]
    if (exact) return exact
    const templated = translateTemplate(value, dictionary)
    return templated !== value ? templated : translateValidationMessage(value, language)
  }
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT)
  const nodes = []
  while (walker.nextNode()) nodes.push(walker.currentNode)
  nodes.forEach((node) => {
    const localized = convert(node.nodeValue)
    if (localized !== node.nodeValue) node.nodeValue = localized
  })
  document.querySelectorAll(attributeNames.map((name) => `[${name}]`).join(',')).forEach((element) => {
    attributeNames.forEach((name) => {
      if (element.hasAttribute(name)) {
        const localized = convert(element.getAttribute(name))
        if (localized !== element.getAttribute(name)) element.setAttribute(name, localized)
      }
    })
  })
}

const LocaleContext = createContext(null)

function initialLanguage() {
  const savedLanguage = window.localStorage.getItem(STORAGE_KEY)
  return savedLanguage === 'en' || savedLanguage === 'ar' ? savedLanguage : 'ar'
}

export function LocaleProvider({ children }) {
  const [language, setLanguage] = useState(initialLanguage)

  useEffect(() => {
    document.documentElement.lang = language
    document.documentElement.dir = language === 'ar' ? 'rtl' : 'ltr'
    document.title = language === 'ar'
      ? 'DANNA | رعاية حديثي الولادة'
      : 'DANNA | Neonatal Care'
    localizeDocument(language)

    const observer = new MutationObserver(() => localizeDocument(language))
    observer.observe(document.body, { childList: true, subtree: true, characterData: true })
    return () => observer.disconnect()
  }, [language])

  const value = useMemo(() => ({
    language,
    direction: language === 'ar' ? 'rtl' : 'ltr',
    setLanguage(nextLanguage) {
      if (nextLanguage !== 'ar' && nextLanguage !== 'en') {
        throw new Error(`Unsupported language: ${nextLanguage}`)
      }

      window.localStorage.setItem(STORAGE_KEY, nextLanguage)
      setLanguage(nextLanguage)
    },
    t(text, variables) {
      if (typeof text !== 'string') return text
      let template = text
      if (language === 'ar') {
        const translation = translations[text] || translateTemplate(text, translations)
        if (translation !== text) {
          template = translation
        } else if (import.meta.env.DEV && text.trim()) {
          console.warn(`[i18n] Missing Arabic translation: "${text}"`)
        }
      }
      if (!variables) return template
      return template.replace(/\{(\w+)\}/g, (match, name) => (
        Object.prototype.hasOwnProperty.call(variables, name) ? String(variables[name]) : match
      ))
    },
  }), [language])

  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>
}

export function useLocale() {
  const context = useContext(LocaleContext)
  if (!context) throw new Error('useLocale must be used within LocaleProvider.')
  return context
}

